export function generatePrayerSteps(prayerId, isFard, madhhabId, gender) {
  const prayer = PRAYERS.find(p => p.id === prayerId) || PRAYERS[0];
  const totalRakahs = isFard ? prayer.fardRakahs : (prayer.sunnahBefore || prayer.sunnahAfter || 2);
  const steps = [];

  // Ният
  steps.push({
    id: 'niyyah',
    rakah: 1,
    title: 'Ният (Намерение)',
    posture: 'INTENTION',
    arabic: 'نَوَيْتُ أَنْ أُصَلِّيَ لِلَّهِ تَعَالَى',
    transcription: 'Навайту ан усаллийа лилляхи та‘аля...',
    translation: `Я намереваюсь ради Аллаха совершить ${isFard ? 'фард' : 'сунну'} намаза ${prayer.nameRu}.`,
    instruction: 'Встаньте лицом к Кибле. Сосредоточьтесь, очистите сердце от мирских мыслей. Намерение формируется в сердце.',
    madhhabNote: madhhabId === 'SUNNAH_SALAFI'
      ? 'По Сунне достаточно намерения в сердце, произносить ният вслух или шепотом не является сунной.'
      : 'Сформулируйте искреннее намерение перед произнесением вступительного такбира.'
  });

  // Такбир
  let takbirDesc = 'Поднимите руки на уровень плеч или мочек ушей.';
  if (madhhabId === 'HANAFI') {
    takbirDesc = gender === 'MALE'
      ? 'Мужчины поднимают руки до уровня мочек ушей, касаясь их большими пальцами. Ладони обращены к Кибле.'
      : 'Женщины поднимают руки до уровня плеч или верха груди, не высовывая кисти из-под платка.';
  } else if (madhhabId === 'SHAFII') {
    takbirDesc = 'Поднимите руки до уровня плеч: кончики пальцев на уровне верхушек ушей, большие пальцы на уровне мочек.';
  } else if (madhhabId === 'SUNNAH_SALAFI') {
    takbirDesc = 'Поднимите руки до уровня плеч или ушей с естественно раскрытыми пальцами, направленными вверх и к Кибле.';
  }

  steps.push({
    id: 'takbeer',
    rakah: 1,
    title: 'Такбир аль-Ихрам',
    posture: 'TAKBEER',
    arabic: 'اللَّهُ أَكْبَرُ',
    transcription: 'Аллаху Акбар',
    translation: 'Аллах Превелик!',
    instruction: takbirDesc,
    madhhabNote: 'Произнесением такбира вы входите в священное состояние молитвы. Посторонние действия запрещены.'
  });

  // Ракааты
  for (let r = 1; r <= totalRakahs; r++) {
    const isFirst = r === 1;
    const isFinal = r === totalRakahs;
    const hasMiddleTashahhud = totalRakahs > 2 && r === 2;
    const reciteExtra = r <= 2;

    // Кыям
    let qiyamInst = 'Сложите руки и стойте прямо, смотря на место земного поклона.';
    if (madhhabId === 'HANAFI') {
      qiyamInst = gender === 'MALE'
        ? 'Руки ниже пупка: правая ладонь охватывает левое запястье большим пальцем и мизинцем. Взгляд — на место суджуда.'
        : 'Руки на груди: правая рука лежит на левой, локти прижаты к телу.';
    } else if (madhhabId === 'SHAFII') {
      qiyamInst = 'Руки чуть выше пупка (под грудью, слегка сместив влево к сердцу). Правая кисть держит левое запястье.';
    } else if (madhhabId === 'MALIKI') {
      qiyamInst = 'Основное положение — руки опущены вдоль тела (садль). Допускается сложить руки на груди (кабд).';
    } else if (madhhabId === 'HANBALI') {
      qiyamInst = 'Сложите руки ниже пупка либо на груди, положив правую кисть на левую руку.';
    } else if (madhhabId === 'SUNNAH_SALAFI') {
      qiyamInst = 'Положите правую кисть на левую кисть, запястье и предплечье строго на груди. Взгляд — на место поклона.';
    }

    const thanaText = madhhabId === 'SHAFII'
      ? 'Вадджахту ваджхийа ли-ллязи фатара-с-самавати валь-арда...'
      : 'Субханака-Ллахумма ва би-хамдика, ва табарака-смука...';

    steps.push({
      id: `qiyam_fatiha_${r}`,
      rakah: r,
      title: isFirst ? 'Кыям: Сана и Сура Аль-Фатиха' : 'Кыям: Сура Аль-Фатиха',
      posture: madhhabId === 'MALIKI' ? 'QIYAM_SADL' : 'QIYAM_FOLDED',
      arabic: isFirst
        ? 'سُبْحَانَكَ اللَّهُمَّ وَبِحَمْدِكَ...\n\nبِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ\nالْحَمْدُ لِلَّهِ رَبِّ الْعَالَمِينَ ۞ الرَّحْمَٰنِ الرَّحِيمِ ۞ مَالِكِ يَوْمِ الدِّينِ ۞ إِيَّاكَ نَعْبُدُ وَإِيَّاكَ نَسْتَعِينُ ۞ اهْدِنَا الصِّرَاطَ الْمُسْتَقِيمَ ۞ صِرَاطَ الَّذِينَ أَنْعَمْتَ عَلَيْهِمْ غَيْرِ الْمَغْضُوبِ عَلَيْهِمْ وَلَا الضَّالِّينَ'
        : 'بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ\nالْحَمْدُ لِلَّهِ رَبِّ الْعَالَمِينَ ۞ الرَّحْمَٰنِ الرَّحِيمِ ۞ مَالِكِ يَوْمِ الدِّينِ ۞ إِيَّاكَ نَعْبُدُ وَإِيَّاكَ نَسْتَعِينُ ۞ اهْدِنَا الصِّرَاطَ الْمُسْتَقِيمَ...',
      transcription: isFirst
        ? `${thanaText}\n\nА‘узу билляхи мина-ш-шайтани-р-раджим.\nБисмилляхи-р-Рахмани-р-Рахим. Аль-хамду лилляхи Рабби-ль-‘алямин...`
        : 'Бисмилляхи-р-Рахмани-р-Рахим. Аль-хамду лилляхи Рабби-ль-‘алямин...',
      translation: 'Хвала Аллаху, Господу миров, Милостивому, Милосердному, Владыке Дня суда. Тебе одному мы поклоняемся...',
      instruction: qiyamInst,
      madhhabNote: isFirst ? 'В 1-м ракаате перед Фатихой читается вступительное дуа (Сана/Истифтах).' : null
    });

    // Дополнительная сура
    if (reciteExtra) {
      const isR1 = r === 1;
      steps.push({
        id: `extra_surah_${r}`,
        rakah: r,
        title: isR1 ? 'Чтение суры (Аль-Ихлас)' : 'Чтение суры (Аль-Фаляк)',
        posture: madhhabId === 'MALIKI' ? 'QIYAM_SADL' : 'QIYAM_FOLDED',
        arabic: isR1
          ? 'قُلْ هُوَ اللَّهُ أَحَدٌ ۞ اللَّهُ الصَّمَدُ ۞ لَمْ يَلِدْ وَلَمْ يُولَدْ ۞ وَلَمْ يَكُن لَّهُ كُفُوًا أَحَدٌ'
          : 'قُلْ أَعُوذُ بِرَبِّ الْفَلَقِ ۞ مِن شَرِّ مَا خَلَقَ ۞ وَمِن شَرِّ غَاسِقٍ إِذَا وَقَبَ ۞ وَمِن شَرِّ النَّفَّاثَاتِ فِي الْعُقَدِ ۞ وَمِن شَرِّ حَاسِدٍ إِذَا حَسَدَ',
        transcription: isR1
          ? 'Куль хува-Ллаху Ахад. Аллаху-с-Самад. Лям йалид ва лям йуляд. Ва лям йакун ляху куфуван ахад.'
          : 'Куль а‘узу би-Рабби-ль-фаляк. Мин шарри ма халяк. Ва мин шарри гасикин иза вакаб...',
        translation: isR1
          ? 'Скажи: «Он — Аллах Единый, Аллах Самодостаточный, не родил и не был рожден, и нет никого, равного Ему».'
          : 'Скажи: «Прибегаю к защите Господа рассвета от зла того, что Он сотворил...»',
        instruction: 'Оставайтесь стоять смирно. Прочтите короткую суру или минимум 3 коротких аята.',
        madhhabNote: 'Чтение дополнительной суры совершается только в первых двух ракаатах.'
      });
    }

    // Витр Ханафи Кунут
    if (prayerId === 'witr' && r === 3 && madhhabId === 'HANAFI') {
      steps.push({
        id: 'witr_qunut',
        rakah: 3,
        title: 'Такбир и Дуа Кунут (Витр)',
        posture: 'TAKBEER',
        arabic: 'اللَّهُ أَكْبَرُ\n\nاللَّهُمَّ إِنَّا نَسْتَعِينُكَ وَنَسْتَغْفِرُكَ وَنَسْتَهْدِيكَ وَنُؤْمِنُ بِكَ وَنَتُوبُ إِلَيْكَ...',
        transcription: 'Аллаху Акбар!\n\nАллахумма инна наста‘инука ва настагфирука ва настахдика...',
        translation: 'Аллах Превелик! О Аллах, мы молим Тебя о помощи, просим о прощении и каемся перед Тобой...',
        instruction: 'После чтения суры поднимите руки со словами «Аллаху Акбар», сложите их снова и прочтите дуа Кунут.',
        madhhabNote: 'В ханафитском мазхабе такбир перед Кунутом с поднятием рук является обязательным (ваджиб).'
      });
    }

    // Рукуъ
    let rukuInst = 'Склонитесь со словами «Аллаху Акбар».';
    if (madhhabId === 'HANAFI') {
      rukuInst = gender === 'MALE'
        ? 'Склонитесь со словами «Аллаху Акбар». Спина строго прямая параллельно полу, пальцы широко расставлены на коленях.'
        : 'Женщины слегка наклоняются (под 45 градусов), колени мягко согнуты, пальцы сомкнуты на коленях, локти прижаты к бокам.';
    } else if (['SHAFII', 'HANBALI', 'SUNNAH_SALAFI'].includes(madhhabId)) {
      rukuInst = 'Поднимите руки со словами «Аллаху Акбар» (раф‘уль-ядейн) и склонитесь в поясной поклон. Спина ровная, руки на коленях.';
    }

    steps.push({
      id: `ruku_${r}`,
      rakah: r,
      title: 'Рукуъ (Поясной поклон)',
      posture: 'RUKU',
      arabic: 'سُبْحَانَ رَبِّيَ الْعَظِيمِ',
      transcription: 'Субхана Раббийа-ль-‘Азыйм (3 раза)',
      translation: 'Пречист мой Господь Великий!',
      instruction: rukuInst,
      repetitions: 3,
      madhhabNote: 'Обязательно задержаться в поклоне в состоянии полного покоя (тума‘нина).'
    });

    // И'тидаль
    let itidalInst = 'Выпрямитесь в положение стоя со словами «Сами‘а-Ллаху ли-ман хамидах», затем скажите «Раббана ва ляка-ль-хамд».';
    if (['SHAFII', 'HANBALI', 'SUNNAH_SALAFI'].includes(madhhabId)) {
      itidalInst = 'Выпрямляясь, поднимите руки до уровня плеч со словами «Сами‘а-Ллаху ли-ман хамидах». Полностью выпрямитесь и скажите «Раббана ва ляка-ль-хамд».';
    }

    steps.push({
      id: `itidal_${r}`,
      rakah: r,
      title: 'И‘тидаль (Выпрямление)',
      posture: 'ITIDAL',
      arabic: 'سَمِعَ اللَّهُ لِمَنْ حَمِدَهُ ، رَبَّنَا وَلَكَ الْحَمْدُ',
      transcription: 'Сами‘а-Ллаху ли-ман хамидах. Раббана ва ляка-ль-хамд',
      translation: 'Услышал Аллах того, кто воздал Ему хвалу. Господь наш, вся хвала Тебе!',
      instruction: itidalInst,
      madhhabNote: (prayerId === 'fajr' && r === 2 && madhhabId === 'SHAFII')
        ? 'В шафиитском мазхабе во 2-м ракаате Фаджра после выпрямления читается дуа Кунут с поднятыми ладонями.'
        : null
    });

    // Саджда 1
    let sujudInst = 'Опуститесь в земной поклон со словами «Аллаху Акбар».';
    if (madhhabId === 'HANAFI') {
      sujudInst = gender === 'MALE'
        ? 'Опуститесь со словами «Аллаху Акбар» (колени, ладони, лоб с носом). Локти оторваны от пола и разведены от боков. Живот не касается бедер.'
        : 'Опуститесь компактно. Локти прижаты к полу и к бокам, живот прижат к бедрам, стопы направлены вправо.';
    } else {
      sujudInst = 'Опуститесь на 7 опорных точек: лоб с носом, обе ладони, оба колена и пальцы обеих стоп, направленные к Кибле. Локти приподняты над ковриком.';
    }

    steps.push({
      id: `sujud1_${r}`,
      rakah: r,
      title: 'Саджда 1 (Земной поклон)',
      posture: 'SUJUD',
      arabic: 'سُبْحَانَ رَبِّيَ الْأَعْلَى',
      transcription: 'Субхана Раббийа-ль-А‘ля (3 раза)',
      translation: 'Пречист мой Господь Всевышний!',
      instruction: sujudInst,
      repetitions: 3,
      madhhabNote: 'Это самое близкое положение раба к Всевышнему Аллаху. Сохраняйте полное благоговение.'
    });

    // Джалса (Сидение между сажда)
    steps.push({
      id: `jalsa_${r}`,
      rakah: r,
      title: 'Джалса (Пауза между сажда)',
      posture: 'SITTING_JALSA',
      arabic: 'رَبِّ اغْفِرْ لِي ، رَبِّ اغْفِرْ لِي',
      transcription: 'Рабби-гфир ли, Рабби-гфир ли',
      translation: 'Господи, прости меня! Господи, прости меня!',
      instruction: gender === 'MALE'
        ? 'Сядьте со словами «Аллаху Акбар» на подогнутую левую стопу, правая стопа стоит вертикально пальцами к Кибле (Ифтираш).'
        : 'Сядьте со словами «Аллаху Акбар», сместив обе ноги вправо и опустившись на левое бедро (Таваррук).',
      madhhabNote: 'Обязательно полностью выпрямить спину перед вторым поклоном.'
    });

    // Саджда 2
    steps.push({
      id: `sujud2_${r}`,
      rakah: r,
      title: 'Саджда 2 (Второй поклон)',
      posture: 'SUJUD',
      arabic: 'سُبْحَانَ رَبِّيَ الْأَعْلَى',
      transcription: 'Субхана Раббийа-ль-А‘ля (3 раза)',
      translation: 'Пречист мой Господь Всевышний!',
      instruction: sujudInst,
      repetitions: 3
    });

    // Промежуточный ташаххуд
    if (hasMiddleTashahhud) {
      steps.push({
        id: 'middle_tashahhud',
        rakah: 2,
        title: 'Первый Ташаххуд (Ат-Тахийят)',
        posture: 'SITTING_TASHAHHUD',
        arabic: 'التَّحِيَّاتُ لِلَّهِ وَالصَّلَوَاتُ وَالطَّيِّبَاتُ ، السَّلَامُ عَلَيْكَ أَيُّهَا النَّبِيُّ وَرَحْمَةُ اللَّهِ وَبَرَكَاتُهُ ، السَّلَامُ عَلَيْنَا وَعَلَى عِبَادِ اللَّهِ الصَّالِحِينَ ، أَشْهَدُ أَنْ لَا إِلَهَ إِلَّا اللَّهُ وَأَشْهَدُ أَنَّ مُحَمَّدًا عَبْدُهُ وَرَسُولُهُ',
        transcription: 'Ат-тахиййату лилляхи вас-салавату ват-таййибат. Ас-саляму ‘алейка аййухан-набиййу ва рахмату-Ллахи ва баракатух. Ас-саляму ‘алейна ва ‘аля ‘ибади-Лляхи-с-салихин. Ашхаду ал-ля иляха илля-Ллаху ва ашхаду анна Мухаммадан ‘абдуху ва расулюх',
        translation: 'Все приветствия Аллаху, молитвы и благие дела. Мир тебе, о Пророк...',
        instruction: 'Сядьте на левую ногу (мужчины) или на бедро с ногами вправо (женщины). Прочтите Ташаххуд. После этого встаньте на 3-й ракаат.',
        madhhabNote: getFingerNote(madhhabId)
      });
    }

    // Заключительное сидение
    if (isFinal) {
      steps.push({
        id: 'final_tashahhud',
        rakah: r,
        title: 'Ташаххуд и Салават',
        posture: 'SITTING_TASHAHHUD',
        arabic: 'التَّحِيَّاتُ لِلَّهِ وَالصَّلَوَاتُ وَالطَّيِّبَاتُ...\n\nاللَّهُمَّ صَلِّ عَلَى مُحَمَّدٍ وَعَلَى آلِ مُحَمَّدٍ...\n\nرَبَّنَا آتِنَا فِي الدُّنْيَا حَسَنَةً وَفِي الْآخِرَةِ حَسَنَةً وَقِنَا عَذَابَ النَّارِ',
        transcription: 'Ат-тахиййату лилляхи... \n\n Аллахумма салли ‘аля Мухаммадин ва ‘аля али Мухаммад... \n\n Раббана атина фид-дунья хасанатан...',
        translation: 'Ат-Тахийят + Салават Пророку ﷺ + Заключительное дуа «Раббана атина»',
        instruction: gender === 'MALE'
          ? (madhhabId === 'HANAFI' ? 'Сидение в позе Ифтираш (на левой стопе, правая вертикально).' : 'Сидение в позе Таваррук (левая стопа под правой голенью, сидение на полу).')
          : 'Сидение в позе Таваррук (ноги выведены вправо, сидение на левом бедре).',
        madhhabNote: getFingerNote(madhhabId)
      });

      // Салям
      if (madhhabId === 'MALIKI') {
        steps.push({
          id: 'salam_right',
          rakah: r,
          title: 'Таслим (Приветствие направо)',
          posture: 'SALAM_RIGHT',
          arabic: 'السَّلَامُ عَلَيْكُمْ وَرَحْمَةُ اللَّهِ',
          transcription: 'Ас-саляму ‘алейкум ва рахмату-Ллах',
          translation: 'Мир вам и милость Аллаха!',
          instruction: 'Поверните голову направо, произнося приветствие. В маликитском мазхабе один салям направо является обязательным выходом из намаза.',
          madhhabNote: 'Намаз завершен! Альхамдулиллях.'
        });
      } else {
        steps.push({
          id: 'salam_right',
          rakah: r,
          title: 'Таслим 1 (Поворот направо)',
          posture: 'SALAM_RIGHT',
          arabic: 'السَّلَامُ عَلَيْكُمْ وَرَحْمَةُ اللَّهِ',
          transcription: 'Ас-саляму ‘алейкум ва рахмату-Ллах',
          translation: 'Мир вам и милость Аллаха!',
          instruction: 'Поверните голову направо так, чтобы щека была видна сзади, приветствуя ангелов и молящихся.'
        });
        steps.push({
          id: 'salam_left',
          rakah: r,
          title: 'Таслим 2 (Поворот налево)',
          posture: 'SALAM_LEFT',
          arabic: 'السَّلَامُ عَلَيْكُمْ وَرَحْمَةُ اللَّهِ',
          transcription: 'Ас-саляму ‘алейкум ва рахмату-Ллах',
          translation: 'Мир вам и милость Аллаха!',
          instruction: 'Поверните голову налево, произнося приветствие. Намаз завершен! Альхамдулиллях.'
        });
      }
    }
  }

  return steps;
}

function getFingerNote(madhhabId) {
  switch (madhhabId) {
    case 'HANAFI':
      return 'Палец поднимается при словах «Ля иляха» и опускается при словах «илля-Ллах».';
    case 'SHAFII':
      return 'Палец поднимается при словах «илля-Ллах» и удерживается неподвижно до завершения саляма.';
    case 'MALIKI':
      return 'Палец плавно двигается вправо-влево на протяжении всего чтения Ташаххуда.';
    case 'HANBALI':
      return 'Палец поднимается/указывает при каждом упоминании имени Аллаха.';
    case 'SUNNAH_SALAFI':
      return 'Палец направлен в сторону Киблы, взгляд устремлен на него, непрерывное легкое шевеление во время дуа.';
    default:
      return 'Указательный палец направлен к Кибле при свидетельстве веры.';
  }
}
